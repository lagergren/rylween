void reganim()
{
	UBYTE i;
	long t;

	time(&t); srand((unsigned int)t);

	/* Please Register */
	/* Blit 15 times with a 30 tick delay */	

	if(rand() % 2) return;

	cl();

	for(i=0 ; i<15 ; i++) {
		c(31,12);
		tx("[3%dmPLEASE REGISTER!",(rand() % 6)+1);
		Delay(4);
	}
	c(31,12);
	tx("[31mPLEASE REGISTER!");
	Delay(150);
	c(30,12); tx("[32m%c",219); Delay(10);
	for(i=30 ; i<48 ; i++) {
		c(i,11);
		if(i % 2) tx("[32m%c",219);
		else tx("[33m%c",219);
		Delay(10);
	}
	c(47,12); tx("[33m%c",219); Delay(10);
	for(i=47 ; i>29 ; i--) {
		c(i,13);
		if(i % 2) tx("[32m%c",219);
		else tx("[33m%c",219);
		Delay(10);
	}
	Delay(100);

	cl();
	//if(!cli) (*XCB->DisplayTextFile)("Doors:RYLWEEN/SCREEN.ANS",CONTINUOUS,TF_PROCESS_TILDE,0,0);
	disptext("Doors:Rylween/SCREEN.ANS");
}

